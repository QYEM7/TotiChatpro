import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
import {existsSync} from 'node:fs';
const candidates=['/usr/bin/google-chrome','/usr/bin/chromium','/usr/bin/chromium-browser'];
const executablePath=candidates.find(existsSync);
if(!executablePath)throw Error('Chromium unavailable');
const browser=await chromium.launch({headless:true,executablePath,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/auth/v1/settings',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({external:{google:true,facebook:false,apple:false}}),headers:{'access-control-allow-origin':'*'}}));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
await page.locator('#google-login').waitFor({timeout:12000});
assert.equal(await page.locator('#google-login').count(),1);
assert.equal(await page.getByText('المتابعة باستخدام Google').count(),1);
assert.equal(await page.locator('[data-act="google"]').count(),1);
assert.equal(await page.locator('[data-act="password"]').count(),0);
assert.equal(await page.locator('[data-act="apple"]').count(),0);
assert.equal(await page.locator('img.login-mark').count(),1);
assert.equal((await page.title()).includes('TotiChat'),true);
assert.deepEqual(errors,[]);
await page.screenshot({path:'/tmp/totichat-reborn-login.png',fullPage:true});
await browser.close();
console.log('PASS: clean TotiChat Google-only login renders on mobile without runtime errors.');
