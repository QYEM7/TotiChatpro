/* Mobile frontend finishing regression; no live account or financial transactions. */
const puppeteer=require('puppeteer-core');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const exe=process.env.CHROME_BIN||['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/usr/bin/chromium-browser'].find(fs.existsSync);
if(!exe)throw new Error('Chromium unavailable');
const base=process.env.UI_URL||'http://127.0.0.1:8765/app/';
const wait=ms=>new Promise(ok=>setTimeout(ok,ms));
(async()=>{
const browser=await puppeteer.launch({headless:true,executablePath:exe,args:['--no-sandbox','--disable-setuid-sandbox']});
const page=await browser.newPage();await page.setViewport({width:390,height:844});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const go=async name=>{await page.evaluate(route=>window.go(route),name);await page.waitForSelector('#app[data-route="'+name+'"]');};
const click=async(selector)=>{await page.$eval(selector,el=>el.click());await wait(35)};
try{
 await page.goto(base+'?view=royal-home',{waitUntil:'domcontentloaded'});
 await page.waitForSelector('.royal-home');
 assert.equal(await page.$$eval('.royal-room-tile',es=>es.length),6);
 await go('loginPreview');
 assert.ok(await page.$('#fc-email'));
 await click('[data-fc="validate-auth"]');
 assert.match(await page.$eval('#fc-form-status',el=>el.textContent),/بريداً إلكترونياً/);
 await page.type('#fc-email','example@example.com');
 await page.type('#fc-pass','abcdefgh12');
 await click('[data-fc="validate-auth"]');
 assert.match(await page.$eval('#fc-form-status',el=>el.textContent),/لا توجد جلسة/);
 await go('signupPreview');
 assert.ok(await page.$('#fc-confirm'));
 await go('passwordResetPreview');
 assert.equal(await page.$eval('#app',el=>el.dataset.route),'passwordResetPreview');
 await go('friendsPreview');
 assert.equal(await page.$$eval('.fc-person',e=>e.length),2);
 await click('[data-fc="social-tab"][data-v="followers"]');
 assert.equal(await page.$$eval('.fc-person',e=>e.length),1);
 await go('storePreview');
 assert.equal(await page.$$eval('.fc-product',e=>e.length),7);
 await click('[data-fc="store-tab"][data-v="frames"]');
 assert.equal(await page.$$eval('.fc-product',e=>e.length),2);
 await click('[data-fc="product"][data-v="f1"]');
 assert.ok(await page.$('#overlay.show .fc-detail-art'));
 assert.equal(await page.$eval('#overlay',el=>el.textContent.includes('يحدده Backend')),true);
 await click('[data-fc="close"]');
 await go('bagPreview');
 assert.ok(await page.$('.fc-empty'));
 await click('[data-fc="bag-tab"][data-v="vehicles"]');
 assert.ok(await page.$('.fc-empty'));
 await go('notificationsPreview');
 await click('[data-fc="alert-tab"][data-v="gifts"]');
 assert.ok(await page.$('.fc-empty'));
 await go('helpCenterPreview');
 assert.ok(await page.$('.fc-faq summary'));
 await go('searchPreview');
 assert.ok(await page.$('#fc-global-q'));
 await go('accountSafetyPreview');
 assert.ok(await page.$('.fc-row[data-v="block"]'));
 await go('report');
 assert.ok(await page.$('#fc-report-text'));
 await click('[data-fc="report-review"]');
 assert.match(await page.$eval('#fc-report-status',e=>e.textContent),/15 حرفاً/);
 await page.type('#fc-report-text','هذا بلاغ معاينة لفحص اكتمال نموذج الدعم.');
 await click('[data-fc="report-review"]');
 assert.ok(await page.$('#overlay.show .fc-sheet'));
 await go('settings');
 assert.ok(await page.$('[data-fc-entry]'));
 const toggle='[data-a="option"][data-v="switch"]';
 const oldSwitch=await page.$eval(toggle,el=>el.querySelector('.switch').classList.contains('on'));
 await click(toggle);
 const changed=await page.$eval(toggle,el=>el.querySelector('.switch').classList.contains('on'));
 assert.notEqual(oldSwitch,changed,'switch should react to tap');
 await go('me');await go('settings');
 assert.equal(await page.$eval(toggle,el=>el.querySelector('.switch').classList.contains('on')),changed,'local preference survives route changes');
 await click('[data-a="option"][data-v="security"]');
 assert.equal(await page.$eval('#app',e=>e.dataset.route),'accountSafetyPreview');

 await go('roomAdminPreview');
 assert.ok(await page.$('[data-rf="rf-room-settings"]'));
 await click('[data-rf="rf-room-settings"]');
 assert.ok(await page.$('#overlay.show #tc-name'),'owner dashboard must open the full room-settings form');
 await page.evaluate(()=>closeSheet());
 await go('room');
 assert.equal(await page.$eval('.seats .seat',e=>e.length),15);
 await go('vip');
 assert.equal(await page.$$eval('.rvip-tier',e=>e.length),15);
 assert.deepEqual(errors,[],'no page errors');
 console.log('PASS frontend finishing: auth validation, social filters, store detail, bag, notifications, help, search, safety, reports and 15 seats / VIP.');
}finally{await browser.close();}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1});
