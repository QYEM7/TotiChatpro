 assert.equal(await p.$eval('.tc-catalog-content',e=>e.querySelector('img')),null,'DB label must be text, never injected markup');
 await p.click('[data-catalog-action="store-filter"][data-catalog-value="frames"]');
 await p.waitForFunction(()=>document.querySelectorAll('[data-catalog-action="store-item"]').length>0&&document.querySelectorAll('[data-catalog-action="store-item"]').length<40);
 await p.click('[data-catalog-action="store-filter"][data-catalog-value=""]');
 await p.waitForFunction(()=>document.querySelectorAll('[data-catalog-action="store-item"]').length===40);
 await p.type('[data-catalog-search]','VIP');
 await p.waitForFunction(()=>document.querySelectorAll('[data-catalog-action="store-item"]').length===8);
 assert.equal(await p.$eval('[data-catalog-search]',e=>e===document.activeElement),true);
 await p.click('[data-catalog-action="store-item"]');
 await p.waitForSelector('#sheet .cardwhite');
 assert.equal(await p.$$('[data-catalog-action="store-buy"]').then(x=>x.length),1);
 await p.evaluate(()=>{closeSheet();go('rechargePreview');});
 await p.waitForFunction(()=>document.querySelectorAll('[data-catalog-action="package"]').length===6);
 assert.equal(await p.$$eval('details',e=>e.length),10);
